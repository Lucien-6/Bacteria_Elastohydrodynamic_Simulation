function pilus_mode_relaxation_pili1()
%PILUS_MODE_RELAXATION_PILI1  Relaxation times of bending orders 1-5, one filament
%
%  Stand-alone script (no dependency on private paper_cases/ or test/).
%  Constructs the example capsule (a = 1.25 um, b = 0.4 um, N_body = 300,
%  neutrally buoyant) with one 3 um linear filament on the axis (site 1,
%  30 segments).  Orders and times come from init_pili_brownian_modes, the
%  same elastohydrodynamic operator used by the thermal scheme.  Two
%  polarisations are kept for each order.
%
%  Author:  Lucien (lucien-6@qq.com)
%  Created: 2026-11-19
%  Updated: 2026-11-24 — made fully self-contained using public src/ API.

root = fileparts(fileparts(mfilename('fullpath')));
addpath(root);
addpath(genpath(fullfile(root, 'src')));
addpath(fullfile(root, 'MATLAB Add-On', ...
    'Suite of functions to perform uniform sampling of a sphere'));

nolog = @(varargin) [];
pili_cfg = struct('type', 'linear', 'length_um', 3, 'site', 1);
[Pili_Matrix, ext] = parse_pili_config(pili_cfg);
params = init_coupled_params( ...
    'geometry_mode',       'parametric', ...
    'minor_axis',          0.4e-6, ...
    'major_axis',          1.25e-6, ...
    'N_body',              300, ...
    'alpha_0',             0, ...
    'E',                   3.279e8, ...
    'r_pili',              3e-9, ...
    'sigma',               0.2, ...
    'mu',                  1e-3, ...
    'rho_bac',             998.232, ...
    'rho_fluid',           998.232, ...
    'Temper',              293.15, ...
    'hydro_radius_factor', sqrt(2), ...
    'seg_per_um',          10, ...
    'N_segments',          30, ...
    'Pili_Matrix',         Pili_Matrix, ...
    'root_coupling',       {ext.root_coupling}, ...
    'motor_torque',        {ext.motor_torque}, ...
    'logf',                nolog, ...
    'logf_file',           nolog);
Z0 = init_coupled_state(params, nolog);
[Z0, params] = adaptive_basis_check(Z0, params);

fprintf('segments = %s, T_0 = %.6g s\n', mat2str(params.N_segments), params.scales.T_0);

bp = init_pili_brownian_modes(Z0, params, 5);
tau_by_order = zeros(5, 2);
for o = 1:5
    t = sort(bp.tau_s(bp.order == o));
    if numel(t) ~= 2
        error('pilus_mode_relaxation_pili1:OrderCount', ...
            'Order %d has %d modes, expected 2.', o, numel(t));
    end
    tau_by_order(o, :) = t(:).';
    fprintf('order %d: %.6g s and %.6g s\n', o, t(1), t(2));
end
next_tau_s = params.scales.T_0 / bp.next_rate;
fprintf('slowest mode beyond order 5: %.6g s (gap ratio %.3f)\n', next_tau_s, bp.gap_ratio);

out_dir = fullfile(root, 'output', 'pilus_bending_modes');
if ~isfolder(out_dir), mkdir(out_dir); end
N_segments = params.N_segments;
T_0 = params.scales.T_0;
gap_ratio = bp.gap_ratio;
bend_share = bp.bend_share;
save(fullfile(out_dir, 'tau_pili1_orders5.mat'), ...
    'tau_by_order', 'next_tau_s', 'N_segments', 'T_0', 'gap_ratio', 'bend_share');
fprintf('wrote %s\n', fullfile(out_dir, 'tau_pili1_orders5.mat'));
end
