function [f_th_dimless, info] = sample_brownian_body_force(Z, params, dt_B_s, rng_stream)
%SAMPLE_BROWNIAN_BODY_FORCE  Thermal generalised body force for one Brownian interval
%
%  Description:
%    Realises the body-only Brownian increment of ONE interval of length
%    dt_B as a constant generalised force/torque acting on the body over
%    that interval ("force realisation", project v8.5.0), instead of an
%    instantaneous displacement kick applied between deterministic segments.
%
%    With the effective 6x6 body mobility M_eff frozen at the interval
%    start, the Euler-Maruyama body increment is
%
%        dU = L_eff * eta * sqrt(dt_B),     L_eff * L_eff' = 2 kB T M_eff,
%
%    with eta ~ N(0, I_6).  The generalised force that produces exactly
%    this increment on the frozen system is
%
%        f_th = M_eff^{-1} * dU / dt_B.
%
%    f_th is then held constant in the ODE right-hand side for the whole
%    interval (ode_coupled_rhs subtracts it from R_global(1:6), following
%    the sign convention R(1:3) = -Eg*g_hat for the applied gravity force).
%    Two consequences follow:
%
%      (a) No root-projection kink.  The pili see the body move CONTINUOUSLY
%          through the fully coupled solve, so their internal degrees of
%          freedom relax hydrodynamically instead of being re-clamped onto a
%          body that has jumped; the spurious high-wavenumber elastic modes
%          excited by discrete kicks vanish.
%
%      (b) Implicit Ito drift.  Expanding the coupled ODE along the interval
%          gives E[dU] = kB T div(M_eff) dt_B + O(dt_B^{3/2}), because
%          E[f_th f_th'] dt_B = 2 kB T M_eff^{-1}.  The thermal drift of the
%          multiplicative-noise SDE is therefore generated by the mobility
%          gradient sampled along the trajectory; the former explicit
%          finite-difference div(M) correction (12 extra coupled solves per
%          step) is no longer required and must NOT be added again.
%
%    This routine is the only place where the Brownian random-number stream
%    is advanced: exactly six normal deviates per call.
%
%  Syntax:
%    [f_th_dimless, info] = sample_brownian_body_force(Z, params, dt_B_s, rng_stream)
%
%  Inputs:
%    Z          - [(7 + 3*sum(N_segments)) x 1] Global state vector at the
%                 interval start (dimensionless)
%    params     - Parameter structure (from init_coupled_params); must
%                 contain .scales.{L_0, T_0, F_0} and .dim.Temper
%    dt_B_s     - Interval length [s] (> 0)
%    rng_stream - RandStream used for the six normal deviates
%
%  Outputs:
%    f_th_dimless - [6x1] Generalised thermal force in the units of the
%                   coupled linear system: rows 1:3 in F_0, rows 4:6 in
%                   F_0*L_0.  Apply as R_global(1:6) - f_th_dimless.
%    info         - Struct with diagnostics:
%                   .eta            [6x1] normal deviates used
%                   .dU_target_dim  [6x1] frozen-mobility target increment
%                                   [m; m; m; rad; rad; rad]
%                   .f_th_dim       [6x1] dimensional force/torque [N; N*m]
%                   .dt_B_s         interval length [s]
%                   .M_eff_dimless  [6x6] mobility used for the inversion
%
%  References:
%    [1] Ermak & McCammon (1978), J. Chem. Phys. 69, 1352.
%    [2] Delong et al. (2015), J. Chem. Phys. 143, 144107.
%
%  Author:  Lucien (lucien-6@qq.com)
%  Created: 2026-09-04

%% Input validation
if ~(isscalar(dt_B_s) && isfinite(dt_B_s) && dt_B_s > 0)
    error('sample_brownian_body_force:InvalidInterval', ...
        'Brownian interval length must be a finite positive scalar, got %.4g s.', dt_B_s);
end

L_0 = params.scales.L_0;
T_0 = params.scales.T_0;
F_0 = params.scales.F_0;

%% Step 1: Effective body mobility and Brownian factor at the interval start
[L_eff, ~, ~, M_eff_dimless] = compute_effective_body_brownian(Z, params);

%% Step 2: Frozen-mobility Euler-Maruyama target increment (dimensional)
eta          = randn(rng_stream, 6, 1);
dU_target    = L_eff * eta * sqrt(dt_B_s);            % [m; m; m; rad; rad; rad]

%% Step 3: Convert to a constant generalised force (dimensionless units)
%  Dimensionless increment: translations in L_0, rotations in rad.
dU_dimless   = [dU_target(1:3) / L_0; dU_target(4:6)];
dt_dimless   = dt_B_s / T_0;
V_dimless    = dU_dimless / dt_dimless;               % [U_0; 1/T_0]

%  M_eff_dimless is symmetrised and SPD-repaired inside
%  compute_effective_body_brownian, so the 6x6 solve is well posed.
f_th_dimless = M_eff_dimless \ V_dimless;

if any(~isfinite(f_th_dimless))
    error('sample_brownian_body_force:NonFiniteForce', ...
        'Thermal generalised force is non-finite; effective mobility may be singular.');
end

%% Step 4: Diagnostics
info = struct();
info.eta            = eta;
info.dU_target_dim  = dU_target;
info.f_th_dim       = [f_th_dimless(1:3) * F_0; f_th_dimless(4:6) * F_0 * L_0];
info.dt_B_s         = dt_B_s;
info.M_eff_dimless  = M_eff_dimless;

end
